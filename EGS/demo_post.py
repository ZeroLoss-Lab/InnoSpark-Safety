    llm_draft_response = "The LLM generated content goes here..." 
    
    # Execute Audit
    print(f"Auditing response (Length: {len(llm_draft_response)} chars)...")
    is_safe, risk_score = auditor.audit_response(llm_draft_response)

    if is_safe:
        print(f"Audit Passed: Content is safe to display. (Max Risk Score: {risk_score:.4f})")
    else:
        print(f"Audit Blocked: Content contains risk. (Max Risk Score: {risk_score:.4f})")